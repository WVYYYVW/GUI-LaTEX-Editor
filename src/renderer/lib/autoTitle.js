// 問われていること（分野名の後ろに「の…」で添える）
const ASPECTS = [
  ['最大・最小', /最大|最小/],
  ['証明', /証明せよ|示せ/],
  ['面積', /面積/],
  ['体積', /体積/],
  ['個数', /何個|個数|何通り/],
  ['一般項', /一般項/],
  ['軌跡', /軌跡/],
];
// この組み合わせは「の…」を付けない（意味が重なる）
const NO_ASPECT = new Set(['積分:面積', '積分:体積', '軌跡と領域:軌跡', '数列:一般項', '場合の数:個数']);

const count = (re, s) => (s.match(re) || []).length;

/**
 * @param {string} body 問題文（LaTeX）
 * @param {'math'|'physics'|'chemistry'} [subject]
 * @returns {string} 題名（問題文が空なら ''）
 */
export function suggestTitle(body, subject = 'math') {
  const src = String(body || '');
  if (!src.trim()) return '';
  const list = TOPICS[subject] || TOPICS.math;
  let best = null;
  let bestScore = 0;
  for (const [name, re, w = 1] of list) {
    const sc = count(re, src) * w;
    if (sc > bestScore) {
      best = name;
      bestScore = sc;
    }
  }
  if (best) {
    const aspect = ASPECTS.find(([, re]) => re.test(src));
    if (aspect && !NO_ASPECT.has(`${best}:${aspect[0]}`) && !best.includes(aspect[0])) return `${best}の${aspect[0]}`;
    return best;
  }
  // 手がかりが無いとき: 最初の一文（数式は取り除く）を短く
  const first = plainSummary(src.replace(/\$[^$]*\$|\\\([\s\S]*?\\\)|\\\[[\s\S]*?\\\]/g, ''), 200)
    .split(/[。．.]/)[0]
    .replace(/^(次の|以下の)/, '')
    .trim();
  return first.length > 16 ? `${first.slice(0, 16)}…` : first;
}
